"""Industry skills loader — generates .fluid/skills.yaml for workspace projects.

Each industry has a bundled YAML file with domain taxonomy, canonical model,
compliance requirements, and common data sources.  The shared ``_tools.yaml``
is merged into every generated skills file so agents know which platforms,
transformations, orchestration engines, and formats FLUID supports.
"""

from __future__ import annotations

import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

import yaml

_SKILLS_DIR = Path(__file__).parent

# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def load_tools() -> Dict[str, Any]:
    """Load the shared FLUID tool catalog from ``_tools.yaml``."""
    tools_path = _SKILLS_DIR / "_tools.yaml"
    with tools_path.open() as f:
        data = yaml.safe_load(f)
    return data.get("tools", {})


def load_industry_skills(name: str) -> Dict[str, Any]:
    """Load an industry-specific skills file by name (e.g. ``telco``).

    Returns the raw YAML dict (without the tools section — that is merged
    separately via :func:`generate_skills_file`).

    Raises ``FileNotFoundError`` if the industry YAML does not exist.
    """
    path = _SKILLS_DIR / f"{name}.yaml"
    if not path.exists():
        raise FileNotFoundError(f"No industry skills file for '{name}' at {path}")
    with path.open() as f:
        return yaml.safe_load(f)


def list_industries() -> List[Dict[str, str]]:
    """Return a list of available industry choices.

    Each entry has ``key`` (file stem), ``label``, and ``description``.
    The list is built dynamically from YAML files in this directory
    (excluding ``_tools.yaml``).

    An ``other`` entry is always appended as the last option.
    """
    choices: List[Dict[str, str]] = []
    for path in sorted(_SKILLS_DIR.glob("*.yaml")):
        if path.name.startswith("_"):
            continue
        try:
            with path.open() as f:
                data = yaml.safe_load(f)
            industry = data.get("industry", {})
            choices.append(
                {
                    "key": path.stem,
                    "label": industry.get("label", path.stem.title()),
                    "description": industry.get("description", ""),
                }
            )
        except Exception:
            continue
    choices.append(
        {
            "key": "other",
            "label": "Other / General",
            "description": "No industry-specific skills — tools catalog only",
        }
    )
    return choices


def generate_skills_file(
    industry: Optional[str],
    output_dir: Path,
    *,
    cli_version: Optional[str] = None,
) -> Path:
    """Generate ``.fluid/skills.yaml`` by merging industry data with the tool catalog.

    Parameters
    ----------
    industry:
        Industry key (e.g. ``telco``, ``retail``).  ``None`` or ``"other"``
        produces a tools-only file.
    output_dir:
        Workspace root directory.  The file is written to
        ``<output_dir>/.fluid/skills.yaml``.
    cli_version:
        FLUID CLI version stamp.  Defaults to the installed version.

    Returns
    -------
    Path to the generated skills file.
    """
    if cli_version is None:
        try:
            from fluid_build import __version__

            cli_version = __version__
        except ImportError:
            cli_version = "unknown"

    tools = load_tools()

    if industry and industry != "other":
        skills = load_industry_skills(industry)
    else:
        skills = {}

    skills["_version"] = cli_version
    skills["_generated"] = datetime.date.today().isoformat()
    skills["tools"] = tools

    fluid_dir = output_dir / ".fluid"
    fluid_dir.mkdir(parents=True, exist_ok=True)
    out_path = fluid_dir / "skills.yaml"

    header = (
        "# Auto-generated by fluid init — shared agentic knowledge for this project.\n"
        "# All FLUID agents read this file for project context.\n"
        "# Update with: fluid skills update\n"
    )
    with out_path.open("w") as f:
        f.write(header)
        yaml.dump(skills, f, default_flow_style=False, sort_keys=False)

    return out_path


def refresh_tools_section(skills_path: Path, *, cli_version: Optional[str] = None) -> None:
    """Update only the ``tools`` and ``_version`` keys in an existing skills file.

    Preserves all other content (industry, domains, compliance, etc.).
    """
    if cli_version is None:
        try:
            from fluid_build import __version__

            cli_version = __version__
        except ImportError:
            cli_version = "unknown"

    with skills_path.open() as f:
        data = yaml.safe_load(f) or {}

    data["tools"] = load_tools()
    data["_version"] = cli_version
    data["_generated"] = datetime.date.today().isoformat()

    header = (
        "# Auto-generated by fluid init — shared agentic knowledge for this project.\n"
        "# All FLUID agents read this file for project context.\n"
        "# Update with: fluid skills update\n"
    )
    with skills_path.open("w") as f:
        f.write(header)
        yaml.dump(data, f, default_flow_style=False, sort_keys=False)
